"""Build docs/coverage-matrix.md from the rules, the offline test results and the lab test log."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml
from sigma.correlations import SigmaCorrelationRule

from detlab import fixtures, sigma_eval

SOURCE_LABEL = {
    ("aws", "cloudtrail"): "CloudTrail",
    ("azure", "signinlogs"): "Entra sign-in",
    ("azure", "auditlogs"): "Entra audit",
}
LEVEL_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "informational": 4}


def _logsource(rule: Any) -> str:
    if isinstance(rule, SigmaCorrelationRule):
        rule = rule.rules[0].rule
    key = (rule.logsource.product, rule.logsource.service)
    return SOURCE_LABEL.get(key, f"{key[0]}/{key[1]}")


def _technique_link(tag: str) -> str:
    tid = tag.upper()
    path = tid.replace(".", "/")
    return f"[{tid}](https://attack.mitre.org/techniques/{path}/)"


def build(root: Path) -> str:
    collection = sigma_eval.load_rules(root / "rules")
    deployed = sigma_eval.deployed_rules(collection)
    results = fixtures.run_offline(root / "rules", root / "tests" / "fixtures")
    lab_file = root / "validation" / "lab-tests.yml"
    lab: dict[str, Any] = yaml.safe_load(lab_file.read_text(encoding="utf-8")) or {} if lab_file.exists() else {}

    deployed.sort(key=lambda r: (LEVEL_ORDER.get(r.level.name.lower() if r.level else "", 9), sigma_eval.rule_name(r)))
    lines = [
        "# Detection coverage matrix",
        "",
        "Generated by `detlab coverage`. Do not edit by hand: change the rules, the fixtures",
        "or `validation/lab-tests.yml` and regenerate.",
        "",
        "- **Offline tests**: fixture cases passed by the offline evaluator (`detlab test`).",
        "  CI also runs the same cases against a real Elasticsearch with the generated ES|QL.",
        "- **Lab test**: the controlled trigger in the real AWS / Entra lab, from",
        "  `validation/lab-tests.yml`. See `docs/testing-guide.md` for each procedure.",
        "",
        "| Rule | Severity | Log source | Tactics | Techniques | Offline tests | Lab test |",
        "|---|---|---|---|---|---|---|",
    ]
    totals = {"rules": 0, "lab_passed": 0}
    for rule in deployed:
        name = sigma_eval.rule_name(rule)
        tags = [t for t in rule.tags if t.namespace == "attack"]
        tactics = ", ".join(t.name for t in tags if not t.name.startswith("t")) or "-"
        techniques = ", ".join(_technique_link(t.name) for t in tags if t.name.startswith("t")) or "-"
        own = [r for r in results if r.rule == name]
        passed = sum(r.passed for r in own)
        offline = f"{passed}/{len(own)}" + (" ✅" if own and passed == len(own) else " ❌")
        entry = lab.get(name) or {}
        status = entry.get("status") or "not run"
        if status == "passed":
            totals["lab_passed"] += 1
            when = f" ({entry['date']})" if entry.get("date") else ""
            status = f"passed{when}"
        totals["rules"] += 1
        level = rule.level.name.lower() if rule.level else "-"
        lines.append(
            f"| `{name}` | {level} | {_logsource(rule)} | {tactics} | {techniques} | {offline} | {status} |"
        )
    lines += [
        "",
        f"**{totals['rules']} rules, {totals['lab_passed']} validated in the live lab.**",
        "",
    ]
    return "\n".join(lines)


def write(root: Path) -> Path:
    out = root / "docs" / "coverage-matrix.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(root), encoding="utf-8", newline="\n")
    return out
