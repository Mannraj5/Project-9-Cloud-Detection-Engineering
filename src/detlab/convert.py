"""Convert the Sigma rules to ES|QL with pySigma and the lab's processing pipeline."""

from __future__ import annotations

import json
from pathlib import Path

from sigma.backends.elasticsearch import ESQLBackend
from sigma.correlations import SigmaCorrelationRule
from sigma.processing.pipeline import ProcessingPipeline

from detlab import sigma_eval

HEADER = "// Generated by `detlab convert` from {source}. Do not edit by hand.\n"


def backend(pipeline_file: Path) -> ESQLBackend:
    pipeline = ProcessingPipeline.from_yaml(pipeline_file.read_text(encoding="utf-8"))
    return ESQLBackend(processing_pipeline=pipeline)


def convert_rules(rules_dir: Path, pipeline_file: Path) -> dict[str, str]:
    """Return {rule name: ES|QL query} for every deployed rule."""
    collection = sigma_eval.load_rules(rules_dir)
    esql = backend(pipeline_file)
    deployed = {sigma_eval.rule_name(r) for r in sigma_eval.deployed_rules(collection)}
    # Detection rules first: a correlation reads its base rules' conversion results, and
    # base rules (generate: false) return no query of their own.
    ordered = sorted(collection.rules, key=lambda r: isinstance(r, SigmaCorrelationRule))
    queries: dict[str, str] = {}
    for rule in ordered:
        if isinstance(rule, SigmaCorrelationRule):
            result = esql.convert_correlation_rule(rule)
        else:
            result = esql.convert_rule(rule)
        if sigma_eval.rule_name(rule) not in deployed:
            continue
        if len(result) != 1:
            raise ValueError(f"{sigma_eval.rule_name(rule)}: expected one query, got {len(result)}")
        queries[sigma_eval.rule_name(rule)] = str(result[0])
    return queries


def rendered_files(rules_dir: Path, pipeline_file: Path) -> dict[str, str]:
    """{file name: content} for the elastic/esql folder."""
    collection = sigma_eval.load_rules(rules_dir)
    base = rules_dir.resolve().parent
    sources = {
        sigma_eval.rule_name(r): Path(str(r.source.path)).resolve().relative_to(base).as_posix()
        for r in sigma_eval.deployed_rules(collection)
    }
    files = {}
    for name, query in convert_rules(rules_dir, pipeline_file).items():
        files[f"{name}.esql"] = HEADER.format(source=sources[name]) + query.rstrip() + "\n"
    return files


def kibana_ndjson(rules_dir: Path, pipeline_file: Path, interval_minutes: int = 10) -> str:
    """Elastic Security detection rules (ES|QL type) as an NDJSON import file.

    The schedule interval is also the look-back window. The correlation rules count over
    ten minutes, so a shorter interval would make them only ever see part of their window.
    Needs internet access: pySigma downloads the MITRE ATT&CK data to fill in tactic and
    technique names.
    """
    collection = sigma_eval.load_rules(rules_dir)
    pipeline = ProcessingPipeline.from_yaml(pipeline_file.read_text(encoding="utf-8"))
    esql = ESQLBackend(processing_pipeline=pipeline, schedule_interval=interval_minutes, schedule_interval_unit="m")
    rules = esql.convert(collection, output_format="siem_rule_ndjson")
    return "".join(json.dumps(rule, ensure_ascii=False) + "\n" for rule in rules)


def write_esql(rules_dir: Path, pipeline_file: Path, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    files = rendered_files(rules_dir, pipeline_file)
    for stale in out_dir.glob("*.esql"):
        if stale.name not in files:
            stale.unlink()
    for name, content in files.items():
        path = out_dir / name
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written
